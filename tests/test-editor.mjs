import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
globalThis.window={};
const {decodeSubtitle,encodeSubtitle}=await import('../js/editor.js');
assert.equal(typeof window.createTrimTimeline,'function','External trim timeline is installed');
assert.equal(typeof window.SubtitleSerializer.toSrt,'function','External subtitle serializer is installed');
assert.equal(typeof window.WaveformPreview.peaks,'function','External waveform utility is installed');
const sample=readFileSync(new URL('./fixtures/sample.srt',import.meta.url),'utf8');
const parsed=decodeSubtitle(sample);
assert.equal(parsed.cues.length,2);
parsed.cues[0].text='Исправленный текст';
const result=window.SubtitleSerializer.toSrt(parsed.cues);
assert.match(result,/Исправленный текст/);
const roundTrip=decodeSubtitle(result);
assert.equal(roundTrip.cues[0].text,'Исправленный текст');
assert.equal(roundTrip.cues[1].start,2);
const vtt=window.SubtitleSerializer.toVtt(parsed.cues);
assert.match(vtt,/WEBVTT/);
assert.equal(decodeSubtitle(vtt).cues.length,2);
console.log('Editor components: imported timeline, waveform, subtitle editing and serialization — PASS');
