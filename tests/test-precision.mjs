import assert from 'node:assert/strict';
import {createEditHistory} from '../js/edit-history.js';
import {clampTime,timelineWindow,positionInWindow,stepFrame,parseTimecode,formatTimecode} from '../js/precision-timeline.js';
let now=1000;
const history=createEditHistory({start:0,end:4},{limit:3,mergeWindow:200,clock:()=>now});
assert.equal(history.canUndo,false);
history.record({start:0.1,end:4},{mergeKey:'drag'});
now+=60;history.record({start:0.2,end:4},{mergeKey:'drag'});
assert.deepEqual(history.undo(),{start:0,end:4},'Merged drag should be one undo action');
assert.equal(history.canUndo,false);
assert.deepEqual(history.redo(),{start:0.2,end:4});
assert.deepEqual(history.undo(),{start:0,end:4});
history.record({start:0.5,end:4});
assert.equal(history.canRedo,false,'Editing after undo invalidates redo');
now+=400;history.record({start:1,end:4});
history.record({start:1,end:3});
history.record({start:1,end:2});
history.record({start:1,end:1.5});
assert.deepEqual(history.current,{start:1,end:1.5});
for(let i=0;i<20;i++)history.undo();
assert.deepEqual(history.current,{start:1,end:4},'History evicts only old snapshots');
history.reset({start:0,end:6});assert.equal(history.canUndo,false);
let selected={start:0,end:3};
let subtitle=createEditHistory([{start:0,end:1,text:'A'}]);
subtitle.record([{start:0,end:1,text:'B'}],{mergeKey:'text-0'});
assert.equal(subtitle.undo()[0].text,'A');
assert.equal(subtitle.redo()[0].text,'B');
assert.equal(parseTimecode('01:02:03.045'),3723.045);
assert.equal(parseTimecode('02:03,4'),123.4);
assert.equal(parseTimecode('1.250'),1.25);
assert.ok(Number.isNaN(parseTimecode('00:65.000')));
const hugeDigits='9'.repeat(400);
assert.ok(Number.isNaN(parseTimecode(hugeDigits)),'Overflowing numeric seconds must be rejected');
assert.ok(Number.isNaN(parseTimecode(`${hugeDigits}:00:00.000`)),'Overflowing hours must be rejected');
assert.equal(parseTimecode('123:00:00.000'),442800,'Long but finite hours remain supported');
assert.equal(formatTimecode(3723.045),'01:02:03.045');
assert.equal(stepFrame(2,25,1,4),2.04);
assert.equal(stepFrame(0,30,-1,4),0);
assert.equal(stepFrame(4,30,1,4),4);
assert.throws(()=>stepFrame(1,0,1,4));
assert.deepEqual(timelineWindow(20,4,10),{start:7.5,end:12.5,span:5,zoom:4});
assert.deepEqual(timelineWindow(20,4,0),{start:0,end:5,span:5,zoom:4});
assert.deepEqual(timelineWindow(20,4,20),{start:15,end:20,span:5,zoom:4});
assert.equal(positionInWindow(10,timelineWindow(20,4,10)),50);
assert.equal(clampTime(25,20),20);
console.log('Precision timeline, timecodes, undo/redo, bounded history: PASS');
